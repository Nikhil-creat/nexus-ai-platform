"use client";
import Link from "next/link";
import { usePathname, useRouter } from "next/navigation";
import { Refine } from "@refinedev/core";
import routerProvider from "@refinedev/nextjs-router";
import dataProviderRest from "@refinedev/simple-rest";
import { QueryClient } from "@tanstack/react-query";
import { useEffect, useState } from "react";
import Shell from "@/components/Shell";
import { demoDataProvider, RESOURCES } from "@/lib/demoData";
import { accessControlProvider, authProvider, Role, useRole } from "@/lib/providers";

// Set NEXT_PUBLIC_REST_URL to point Refine at a real REST API (e.g. one generated by schema_inspector).
const REST = process.env.NEXT_PUBLIC_REST_URL;
const dataProvider = REST ? dataProviderRest(REST) : demoDataProvider;

const TOOLS = [
  ["/admin/studio", "Schema Studio"],
  ["/admin/knowledge", "Knowledge"],
  ["/admin/workflows", "Workflows"],
  ["/admin/audit", "Audit trail"],
  ["/admin/settings", "Settings"],
];

export default function AdminLayout({ children }: { children: React.ReactNode }) {
  const path = usePathname();
  const router = useRouter();
  const { role, setRole } = useRole();
  const [qc] = useState(() => new QueryClient());
  const [user, setUser] = useState<string | null>(null);

  useEffect(() => {
    let u: string | null = null;
    try { u = sessionStorage.getItem("nexus_auth"); } catch { /* blocked storage */ }
    if (!u) router.replace("/login");
    else setUser(u);
  }, [router]);

  if (!user) return null;

  const logout = () => {
    try { sessionStorage.removeItem("nexus_auth"); sessionStorage.removeItem("nexus_token"); } catch { /* ignore */ }
    router.push("/");
  };
  const link = (href: string, label: string) => (
    <Link key={href} href={href} className={`admin__link ${path === href ? "is-active" : ""}`}>{label}</Link>
  );

  return (
    <Refine
      dataProvider={dataProvider}
      routerProvider={routerProvider}
      authProvider={authProvider}
      accessControlProvider={accessControlProvider}
      resources={Object.entries(RESOURCES).map(([name, r]) => ({ name, list: `/admin/${name}`, meta: { label: r.label } }))}
      options={{ syncWithLocation: false, warnWhenUnsavedChanges: false, reactQuery: { clientConfig: qc } }}
    >
      <Shell>
        {() => (
          <div className="admin">
            <aside className="admin__side">
              <Link href="/" className="admin__brand">NEXUS</Link>
              {link("/admin", "Overview")}
              {Object.entries(RESOURCES).map(([name, r]) => link(`/admin/${name}`, r.label))}
              {TOOLS.map(([href, label]) => link(href, label))}
              <label className="admin__link" style={{ marginTop: "auto" }}>
                Role (RBAC demo)
                <select value={role} onChange={(e) => setRole(e.target.value as Role)} className="input" style={{ marginTop: 8, background: "#000" }}>
                  <option>admin</option><option>editor</option><option>viewer</option>
                </select>
              </label>
              <button className="admin__link" style={{ background: "none", border: 0, textAlign: "left", cursor: "pointer" }} onClick={logout}>
                Sign out · {user}
              </button>
            </aside>
            <section className="admin__main">{children}</section>
          </div>
        )}
      </Shell>
    </Refine>
  );
}
